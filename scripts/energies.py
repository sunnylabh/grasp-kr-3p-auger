"""Binding energies and Auger kinetic energies from the GRASP total energies.

Reads runs/<name>/<name>.cm via rlevels and writes results/energies.md.
KE = E(Kr+ 3p^-1 level) - E(Kr2+ 3d^-1 4p^-1 level).
"""
import os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNS = os.path.join(ROOT, 'runs')
HARTREE = 27.211386245988          # eV
GRASP_BIN = os.environ.get('GRASP_BIN', os.path.expanduser('~/grasp/bin'))

# experiment / literature
NIST_3P = {'3/2': 214.4, '1/2': 222.2}
LIT_KE = {'3/2': '90-94', '1/2': '98-102'}


def levels(name, cm=None):
    """[(J, parity, total energy in Hartree)] from rlevels."""
    cm = cm or f'{name}.cm'
    out = subprocess.run([os.path.join(GRASP_BIN, 'rlevels'), cm], cwd=os.path.join(RUNS, name),
                         capture_output=True, text=True).stdout
    rows, sep = [], 0
    for line in out.splitlines():
        if line.startswith('-----'):
            sep += 1
            continue
        if sep == 2 and line.split():
            p = line.split()
            rows.append((p[2], p[3], float(p[4])))
    return rows


def lowest(rows, j):
    return min(e for jj, _, e in rows if jj == j)


neu = levels('neutral')[0][2]
p5 = levels('p5')
ci = levels('p5_ci', 'p5ci.cm')
fin = [e for _, _, e in levels('d9p5')]

L = ['# Kr 3p hole: GRASP2018 energies', '',
     'Generated by `scripts/energies.py`. All values in eV.', '',
     '## 3p binding energies', '',
     '| Hole | Single configuration | With 3p⁻¹–3d⁻²4f | NIST | Error (corr.) |',
     '|---|---|---|---|---|']
be = {}
for j, lab in [('3/2', '3p₃/₂ (M3)'), ('1/2', '3p₁/₂ (M2)')]:
    sc, c = (lowest(p5, j) - neu) * HARTREE, (lowest(ci, j) - neu) * HARTREE
    be[j] = (sc, c)
    L.append(f'| {lab} | {sc:.2f} | {c:.2f} | {NIST_3P[j]} | {c - NIST_3P[j]:+.2f} |')
L.append(f'| spin-orbit splitting | {be["1/2"][0] - be["3/2"][0]:.2f} | '
         f'{be["1/2"][1] - be["3/2"][1]:.2f} | 7.8 | |')
L += ['', '## M2,3-M4,5N2,3 Coster–Kronig (Kr⁺ 3p⁻¹ → Kr²⁺ 3d⁻¹4p⁻¹)', '',
      'Final state: single configuration, all 12 levels. KE range = lowest to highest final level.', '',
      '| Hole | KE, single configuration | KE, 3p⁻¹ correlated | Literature |', '|---|---|---|---|']
for j, lab in [('3/2', '3p₃/₂ (M3)'), ('1/2', '3p₁/₂ (M2)')]:
    r = lambda e0: f'{(e0 - max(fin)) * HARTREE:.1f}–{(e0 - min(fin)) * HARTREE:.1f}'
    L.append(f'| {lab} | {r(lowest(p5, j))} | {r(lowest(ci, j))} | {LIT_KE[j]} |')
os.makedirs(os.path.join(ROOT, 'results'), exist_ok=True)
open(os.path.join(ROOT, 'results', 'energies.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
